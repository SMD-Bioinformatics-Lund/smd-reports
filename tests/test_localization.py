"""English source labels and explicit report-language translation boundaries."""

import pytest

from smd_reports import ReportRenderer
from smd_reports.localization import label, localized_text
from smd_reports.rendering import display


def test_english_defaults_render_in_swedish_when_requested(payloads, load):
    payload = payloads["generic"]
    payload["language"] = "sv"
    payload["sections"] = [
        {"kind": "table", "key": "empty", "columns": {"en": ["Value"]}},
        {"kind": "summary", "key": "summary", "text": "Example"},
    ]
    report = load(payload)
    assert report.template_name == "Report"
    assert report.resolved_layout.metadata_heading == "Report information"
    assert report.branding.accreditation_label == "Accreditation"
    assert report.sections[0].empty_text == "No reportable results"
    assert report.sections[1].heading == "Conclusion"
    html = ReportRenderer().render_html(report)
    assert "Rapportinformation" in html and "Inga rapporterbara resultat" in html
    assert 'class="report_header">Slutsats</h2>' in html
    assert "Rapport · Mall" in html
    assert '"Sida " counter(page) " av " counter(pages)' in html


def test_english_example_contains_only_english_interface_and_center_details(payloads, load):
    payload = payloads["coyote3-dna"]
    payload["language"] = "en"
    html = ReportRenderer().render_html(load(payload))
    for expected in [
        "Sample information",
        "Generated at",
        "Generated by",
        "Sample ID",
        "Molecular diagnostics",
        "Example address 1",
    ]:
        assert expected in html
    for untranslated in [
        "Provinformation",
        "Rapportdatum",
        "Skapad av",
        "Molekylär diagnostik",
        "Exempeladress 1",
    ]:
        assert untranslated not in html


@pytest.mark.parametrize(
    "language,department,address",
    [
        ("en", "Molecular diagnostics", "Example address 1"),
        ("sv", "Molekylär diagnostik", "Exempeladress 1"),
    ],
)
def test_branding_selects_language_without_translating_literal_names(
    payloads, load, language, department, address
):
    payload = payloads["generic"]
    payload["language"] = language
    payload["branding"].update(
        organization="Report",
        department={"en": "Molecular diagnostics", "sv": "Molekylär diagnostik"},
        address={"en": "Example address 1", "sv": "Exempeladress 1"},
    )
    html = ReportRenderer().render_html(load(payload))
    assert "<span>Report</span>" in html
    assert f"<span>{department}</span>" in html
    assert f'class="report-center-address">{address}</span>' in html
    assert 'alt="Report"' in html


def test_explicit_translation_text_is_not_translated_a_second_time():
    assert label({"en": "Rapport", "sv": "Custom title"}, "en") == "Rapport"
    assert localized_text("Report", "sv") == "Report"
    assert localized_text({"sv": "Exempel"}, "en") == "Exempel"
    assert localized_text({"en": "Example"}, "sv") == "Example"


def test_legacy_source_labels_and_boolean_values_keep_their_output():
    assert label("Provinformation", "en") == "Sample information"
    assert label("Sample information", "sv") == "Provinformation"
    assert label("Provinformation", "sv") == "Provinformation"
    assert display(False, "en") == "No"
    assert display(False, "sv") == "Nej"
    assert display(True, "en") == "Yes"
    assert display(True, "sv") == "Ja"
