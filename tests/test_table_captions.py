"""Explicit captions, neutral reference tables and legacy rendering compatibility."""

import re

import pytest
from pydantic import ValidationError

from smd_reports import ReportLoader, ReportRenderer
from smd_reports.rendering import _offline_url_fetcher


def sections():
    return [
        {
            "kind": "compact_table",
            "key": "genes",
            "caption": "Table 1: Genes",
            "items": ["CALR", "JAK2", "MPL"],
        },
        {
            "kind": "table",
            "key": "reference",
            "caption": {
                "en": "Table 2: Classification",
                "sv": "Tabell 2: Förklaring av klassificering",
            },
            "style": "reference",
            "show_header": False,
            "columns": {"sv": ["", ""]},
            "column_options": {"0": {"width": 1}, "1": {"width": 12}},
            "rows": [
                ["Tier I", "Variant av stark klinisk signifikans enligt gällande riktlinjer"],
                ["Tier II", "Variant av potentiell klinisk signifikans"],
            ],
        },
    ]


def report(payloads, load, definitions):
    data = payloads["generic"]
    data.update(language="sv", sections=definitions)
    return load(data)


@pytest.mark.parametrize("empty", [False, True])
def test_captions_are_shared_localized_literal_and_visible_when_empty(payloads, load, empty):
    definitions = sections()
    definitions[0]["caption"] = "Generated by"
    definitions[0]["heading"] = "Independent heading"
    if empty:
        definitions[0]["items"] = []
        definitions[1]["rows"] = []
    document = report(payloads, load, definitions)
    html = ReportRenderer().render_html(document)
    assert html.count('<figure class="report-table-figure">') == 2
    assert (
        '<figcaption class="table-caption" id="genes-table-caption">Generated by</figcaption>'
        in html
    )
    assert ">Independent heading</h2>" in html
    assert ">Tabell 2: Förklaring av klassificering</figcaption>" in html
    if empty:
        assert html.count('class="empty"') == 2
    else:
        assert html.count('aria-labelledby="genes-table-caption"') == 1
        assert html.count('aria-labelledby="reference-table-caption"') == 1
        assert "<thead>" not in html
    restored = ReportLoader().loads(document.model_dump_json())
    assert ReportRenderer().render_html(restored) == html


def test_omitted_options_preserve_legacy_markup(payloads, load):
    definitions = sections()
    for section in definitions:
        section.pop("caption")
        section["heading"] = "Legacy heading"
    definitions[1].pop("style")
    definitions[1].pop("show_header")
    html = ReportRenderer().render_html(report(payloads, load, definitions))
    assert '<p class="compact-caption"><strong>Legacy heading</strong></p>' in html
    assert ">Legacy heading</h2>" in html
    assert '<figure class="report-table-figure">' not in html
    assert '<thead><tr><th scope="col"></th><th scope="col"></th></tr></thead>' in html


@pytest.mark.parametrize(
    "change", [{"style": "css"}, {"caption": {}}, {"caption": 123}, {"rows": [["Tier I"]]}]
)
def test_reference_options_retain_strict_validation(payloads, load, change):
    definition = sections()[1]
    definition.update(change)
    with pytest.raises(ValidationError):
        report(payloads, load, [definition])


def test_caption_escaping(payloads, load):
    definition = sections()[0]
    definition["caption"] = '<script>alert("caption")</script>'
    html = ReportRenderer().render_html(report(payloads, load, [definition]))
    assert "<script>" not in html
    assert "&lt;script&gt;" in html


@pytest.mark.parametrize("show_header", [False, True])
def test_pdf_geometry_caption_width_borders_typography_and_no_header(payloads, load, show_header):
    weasyprint = pytest.importorskip("weasyprint")
    definitions = sections()
    definitions[1]["show_header"] = show_header
    definitions[1]["row_options"] = {"0": {"highlight": True}}
    definitions[1]["column_options"]["0"]["highlight"] = True
    document = report(payloads, load, definitions)
    rendered = weasyprint.HTML(
        string=ReportRenderer().render_html(document), url_fetcher=_offline_url_fetcher()
    ).render()
    boxes = [box for page in rendered.pages for box in page._page_box.descendants()]
    captions = [
        box for box in boxes if type(box).__name__ == "BlockBox" and box.element_tag == "figcaption"
    ]
    tables = [
        box
        for box in boxes
        if type(box).__name__ == "TableBox"
        and any(name in box.element.get("class", "") for name in ["compact-table", "variant_table"])
    ]
    assert len(captions) == len(tables) == 2
    assert captions[0].width == pytest.approx(captions[1].width)
    assert captions[0].width > tables[0].width * 2
    for caption in captions:
        assert caption.style["font_size"] == pytest.approx(9.25 * 96 / 72)
        assert caption.style["font_weight"] == 600
        assert caption.style["text_align_all"] == "left"
        assert tuple(caption.style["color"].coordinates) == (0, 0, 0)
    cells = [box for box in tables[1].descendants() if type(box).__name__ == "TableCellBox"]
    assert len(cells) == (6 if show_header else 4)
    for cell in cells:
        assert cell.element_tag in {"th", "td"}
        assert cell.style["font_size"] == pytest.approx(8.25 * 96 / 72)
        assert cell.padding_top == cell.padding_bottom == 2
        assert cell.padding_left == cell.padding_right == 4
        assert (
            cell.border_top_width
            == cell.border_bottom_width
            == cell.border_left_width
            == cell.border_right_width
            == 0.5
        )
        assert tuple(cell.style["background_color"].coordinates) == (1, 1, 1)
    assert cells[1].border_width() / cells[0].border_width() == pytest.approx(12, rel=0.02)


def test_long_reference_pdf_preserves_rows_and_caption_with_first_row(payloads, load):
    pytest.importorskip("weasyprint")
    pymupdf = pytest.importorskip("pymupdf")
    definition = sections()[1]
    definition["rows"] = [
        [f"ROW-{index:03d}", "Förklaring av klinisk signifikans. " * 8] for index in range(60)
    ]
    document = report(
        payloads,
        load,
        [{"kind": "text", "key": "preface", "text": "\n".join(["Prelude"] * 37)}, definition],
    )
    with pymupdf.open(stream=ReportRenderer().render_pdf(document), filetype="pdf") as pdf:
        assert len(pdf) > 1
        words = [word for page in pdf for word in page.get_text("words")]
        assert [word[4] for word in words if re.fullmatch(r"ROW-\d+", word[4])] == [
            f"ROW-{index:03d}" for index in range(60)
        ]
        caption_page = next(
            page
            for page in pdf
            if "Förklaring av klassificering" in " ".join(page.get_text().split())
        )
        assert "ROW-000" in caption_page.get_text()
        assert sum(page.get_text().count("klinisk") for page in pdf) == 60 * 8
        for page in pdf:
            for word in page.get_text("words"):
                if word[4].startswith("ROW-"):
                    assert 40 < word[0] < word[2] < page.rect.width - 40
                    assert 0 < word[1] < word[3] < page.rect.height
