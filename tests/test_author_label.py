"""Configurable author captions in JSON, screen metadata and repeated PDF headers."""

import json

import pytest
from pydantic import ValidationError

from smd_reports import ReportLoader, ReportRenderer


@pytest.mark.parametrize("preset", ["generic", "coyote3", "genexus", "cll_genie", "pgx"])
@pytest.mark.parametrize("language,caption", [("en", "Generated by"), ("sv", "Skapad av")])
def test_omitted_and_null_author_labels_keep_default_captions(
    payloads, load, preset, language, caption
):
    data = payloads["generic"]
    data.update(preset=preset, language=language)
    omitted = ReportRenderer().render_html(load(data))
    data["report"]["author_label"] = None
    assert ReportRenderer().render_html(load(data)) == omitted
    assert omitted.count(f">{caption}</th>") == 2


@pytest.mark.parametrize(
    "language,caption,expected",
    [
        ("sv", "Prepared by", "Prepared by"),
        ("sv", "Sample ID", "Sample ID"),
        ("sv", {"en": "Prepared by", "sv": "Sammanställd av"}, "Sammanställd av"),
        ("en", {"en": "Prepared by", "sv": "Sammanställd av"}, "Prepared by"),
        ("sv", {"en": "Prepared by"}, "Prepared by"),
        ("en", {"sv": "Sammanställd av"}, "Sammanställd av"),
        ("en", "", ""),
        ("sv", {"sv": ""}, ""),
        (
            "en",
            '<script>alert("label")</script>',
            "&lt;script&gt;alert(&#34;label&#34;)&lt;/script&gt;",
        ),
    ],
)
def test_custom_author_labels_render_literally_and_round_trip(
    payloads, load, language, caption, expected
):
    data = payloads["generic"]
    data["language"] = language
    data["report"].update(author="AUTHOR-MARKER", author_label=caption)
    report = load(data)
    html = ReportRenderer().render_html(report)
    assert f">{expected}</th><td>AUTHOR-MARKER</td>" in html
    assert html.count("AUTHOR-MARKER") == 2
    assert ">Generated by</th>" not in html and ">Skapad av</th>" not in html
    assert '<script>alert("label")</script>' not in html
    restored = ReportLoader().loads(report.model_dump_json())
    assert restored.metadata.author_label == caption
    assert ReportRenderer().render_html(restored) == html


@pytest.mark.parametrize("caption", [42, True, [], {}, {"de": "Author"}, {"en": 42}])
def test_invalid_author_labels_fail_json_validation(payloads, load, caption):
    data = payloads["generic"]
    data["report"]["author_label"] = caption
    with pytest.raises(ValidationError, match="author_label"):
        load(data)


def test_schema_exposes_optional_author_label_and_cli_preserves_it(tmp_path, payloads, load):
    from smd_reports.cli import main

    schema = ReportLoader().schema()["$defs"]["ReportMetadata"]
    assert schema["properties"]["author_label"]["default"] is None
    assert "author_label" not in schema["required"]
    data = payloads["generic"]
    data["report"].update(author="AUTHOR-MARKER", author_label={"en": "Prepared by"})
    source = tmp_path / "input.json"
    source.write_text(load(data).model_dump_json())
    output = tmp_path / "report.html"
    assert main(["render", str(source), "--format", "html", "--output", str(output)]) == 0
    assert ">Prepared by</th><td>AUTHOR-MARKER</td>" in output.read_text()
    assert json.loads(source.read_text())["report"]["author_label"] == {"en": "Prepared by"}


@pytest.mark.parametrize("language,caption", [("en", "Prepared by"), ("sv", "Sammanställd av")])
def test_author_label_repeats_on_every_pdf_page(payloads, load, language, caption):
    pytest.importorskip("weasyprint")
    pymupdf = pytest.importorskip("pymupdf")
    data = payloads["coyote3-dna"]
    data["language"] = language
    data["report"].update(
        author="AUTHOR-MARKER", author_label={"en": "Prepared by", "sv": "Sammanställd av"}
    )
    pdf = ReportRenderer().render_pdf(load(data))
    with pymupdf.open(stream=pdf, filetype="pdf") as document:
        assert len(document) > 1
        for page in document:
            text = " ".join(page.get_text().split())
            assert caption in text and "AUTHOR-MARKER" in text
            assert "Generated by" not in text and "Skapad av" not in text


@pytest.mark.parametrize(
    "key,default",
    [
        ("sample_id_label", "Sample ID"),
        ("generated_at_label", "Generated at"),
        ("report_id_label", "Report ID"),
    ],
)
@pytest.mark.parametrize("language", ["en", "sv"])
def test_every_automatic_caption_can_be_overridden(payloads, load, key, default, language):
    data = payloads["generic"]
    data["language"] = language
    data["report"]["sample_id"] = "SAMPLE-MARKER"
    data["report"][key] = {"en": "CUSTOM-EN", "sv": "CUSTOM-SV"}
    report = load(data)
    html = ReportRenderer().render_html(report)
    assert html.count(f">CUSTOM-{language.upper()}</th>") == 2
    restored = ReportLoader().loads(report.model_dump_json())
    assert ReportRenderer().render_html(restored) == html
    data["report"][key] = None
    assert "CUSTOM-" not in ReportRenderer().render_html(load(data))
    assert key in ReportLoader().schema()["$defs"]["ReportMetadata"]["properties"]


def test_all_custom_captions_repeat_in_pdf_headers(payloads, load):
    pytest.importorskip("weasyprint")
    pymupdf = pytest.importorskip("pymupdf")
    data = payloads["coyote3-dna"]
    labels = {
        key: f"CAPTION-{index}"
        for index, key in enumerate(
            ["author_label", "sample_id_label", "generated_at_label", "report_id_label"]
        )
    }
    data["report"].update(labels)
    with pymupdf.open(stream=ReportRenderer().render_pdf(load(data)), filetype="pdf") as document:
        for page in document:
            text = " ".join(page.get_text().split())
            assert all(caption in text for caption in labels.values())
